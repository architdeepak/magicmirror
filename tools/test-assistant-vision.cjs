const assert = require('assert/strict');
const fs = require('fs/promises');
const path = require('path');
(async () => {
  const source = await fs.readFile(path.join(__dirname, '../src/assistantVision.js'), 'utf8');
  const { selectAssistantVision } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
  const camera = { srcObject: { active: true }, readyState: 4, videoWidth: 1280, videoHeight: 720 };
  const neural = { ...camera, hidden: false };
  const garmentCanvas = { width: 720, height: 1280 }, effectCanvas = { width: 720, height: 1280 };
  const config = { mode: 'ar', desktopActive: false, camera, neural, neuralState: { active: true, state: 'connecting', frameAgeMs: null }, view: 'live', width: 720, height: 1280, garmentCanvas, effectCanvas };
  assert.equal(selectAssistantVision(config), null, 'Connecting neural view fell back to raw camera');
  config.neuralState = { active: true, state: 'streaming', frameAgeMs: 10 };
  const output = selectAssistantVision(config); assert.equal(output.kind, 'live-ai-try-on');
  const operations = [];
  const context = { save() {}, restore() {}, translate: (...args) => operations.push(['translate', ...args]), scale: (...args) => operations.push(['scale', ...args]), drawImage: (...args) => operations.push(['image', ...args]), fillRect() {} };
  output.draw(context, 360, 640);
  assert(operations.some(op => op[0] === 'scale' && op[1] === -1));
  assert.equal(operations.find(op => op[0] === 'image')[1], neural);
  config.neuralState.frameAgeMs = 4000; assert.equal(selectAssistantVision(config), null);
  config.neuralState.active = false; operations.length = 0;
  const local = selectAssistantVision(config); assert.equal(local.kind, 'local-try-on'); local.draw(context, 360, 640);
  assert.deepEqual(operations.filter(op => op[0] === 'image').map(op => op[1]), [camera, garmentCanvas, effectCanvas]);
  config.cameraCanvas = { width: 720, height: 1280, style: { display: 'block' } }; operations.length = 0;
  selectAssistantVision(config).draw(context, 360, 640);
  assert.deepEqual(operations.filter(op => op[0] === 'image').map(op => op[1]), [config.cameraCanvas, garmentCanvas, effectCanvas]);
  config.cameraCanvas.style.display = 'none'; operations.length = 0; selectAssistantVision(config).draw(context, 360, 640);
  assert.equal(operations.find(op => op[0] === 'image')[1], camera);
  config.view = 'rendered'; config.still = { complete: true, naturalWidth: 1000, naturalHeight: 500 };
  assert.equal(selectAssistantVision(config).kind, 'rendered-try-on-still');
  config.still.complete = false; assert.equal(selectAssistantVision(config), null);
  config.mode = 'watch'; assert.equal(selectAssistantVision(config).kind, 'camera');
  camera.srcObject.active = false; assert.equal(selectAssistantVision(config), null);
  console.log('Assistant vision selection passed: actual neural view, withheld pending/stale output, mirrored local layers, rendered still, and camera availability.');
})().catch(error => { console.error(error); process.exitCode = 1; });
